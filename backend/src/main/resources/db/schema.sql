CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_role_chk CHECK (role IN ('CREATOR', 'TESTER')),
    CONSTRAINT users_email_chk CHECK (POSITION('@' IN email) > 1)
);

CREATE TABLE IF NOT EXISTS games (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_id BIGINT NOT NULL,
    title VARCHAR(150) NOT NULL,
    description TEXT,
    genre VARCHAR(80),
    platform VARCHAR(20) NOT NULL,
    file_path_or_url VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT games_creator_fk
        FOREIGN KEY (creator_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT games_platform_chk
        CHECK (platform IN ('PC', 'WEBGL', 'PRINT_AND_PLAY')),
    CONSTRAINT games_title_chk CHECK (LENGTH(TRIM(title)) > 0)
);

ALTER TABLE games ADD COLUMN IF NOT EXISTS version VARCHAR(20) NOT NULL DEFAULT '1.0';

CREATE TABLE IF NOT EXISTS forms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id BIGINT NOT NULL,
    title VARCHAR(150) NOT NULL,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT forms_game_fk
        FOREIGN KEY (game_id) REFERENCES games (id) ON DELETE CASCADE,
    CONSTRAINT forms_title_chk CHECK (LENGTH(TRIM(title)) > 0)
);

CREATE TABLE IF NOT EXISTS questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id BIGINT NOT NULL,
    question_text TEXT NOT NULL,
    question_type VARCHAR(20) NOT NULL,
    is_required BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT questions_form_fk
        FOREIGN KEY (form_id) REFERENCES forms (id) ON DELETE CASCADE,
    CONSTRAINT questions_type_chk
        CHECK (question_type IN ('LIKERT_1_5', 'TEXT', 'NUMERIC')),
    CONSTRAINT questions_text_chk CHECK (LENGTH(TRIM(question_text)) > 0),
    CONSTRAINT questions_form_id_unique UNIQUE (form_id, id)
);

CREATE TABLE IF NOT EXISTS responses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id BIGINT NOT NULL,
    tester_id BIGINT NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT responses_form_fk
        FOREIGN KEY (form_id) REFERENCES forms (id) ON DELETE CASCADE,
    CONSTRAINT responses_tester_fk
        FOREIGN KEY (tester_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT responses_form_id_unique UNIQUE (form_id, id)
);

CREATE TABLE IF NOT EXISTS answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    response_id BIGINT NOT NULL,
    question_id BIGINT NOT NULL,
    answer_text TEXT,
    numeric_value NUMERIC(10, 2),
    CONSTRAINT answers_response_fk
        FOREIGN KEY (response_id) REFERENCES responses (id) ON DELETE CASCADE,
    CONSTRAINT answers_question_fk
        FOREIGN KEY (question_id) REFERENCES questions (id) ON DELETE RESTRICT,
    CONSTRAINT answers_response_question_unique UNIQUE (response_id, question_id),
    CONSTRAINT answers_value_chk CHECK (answer_text IS NOT NULL OR numeric_value IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_games_creator_id ON games (creator_id);
CREATE INDEX IF NOT EXISTS idx_forms_game_id ON forms (game_id);
CREATE INDEX IF NOT EXISTS idx_questions_form_id ON questions (form_id);
CREATE INDEX IF NOT EXISTS idx_responses_form_id ON responses (form_id);
CREATE INDEX IF NOT EXISTS idx_responses_tester_id ON responses (tester_id);
CREATE INDEX IF NOT EXISTS idx_answers_response_id ON answers (response_id);
